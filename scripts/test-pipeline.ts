async function deleteTestBills() {
  const result = await prisma.project.deleteMany({ where: { title: TITLE } });
  console.log(`Устгасан тест төсөл: ${result.count}`);
}

async function main() {
  // 0. Өмнөх тест төслийг устгана (--delete бол зөвхөн устгаад дуусна)
  await deleteTestBills();
  if (process.argv.includes("--delete")) {
    return;
  }

  // 1. Төсөл оруулах (AI: readAmendment + explainChange)
  console.log("══ 1. Төсөл оруулж байна...");
  const id = await createBill({
    title: TITLE,
    stage: "FIRST_READING",
    currentLawText: LAW_TEXT,
    amendmentText: BILL_TEXT,
    reasonText: REASON_TEXT,
  });

  let detail = await getBillDetail(id, true);
  for (const c of detail!.clauses) {
    console.log(`   ${c.number.padEnd(5)} ${c.changeType.padEnd(8)} ${c.applyError ? "⚠️ " + c.applyError : "✓"}`);
    console.log(`         хуучин: ${c.oldText ?? "—"}`);
    console.log(`         шинэ  : ${c.newText ?? "—"}`);
    console.log(`         яагаад: ${c.why ?? "—"}`);
  }

  // 2. 12.3 дээр 20 санал нэмнэ
  const clause123 = detail!.clauses.find((c) => c.number === "12.3");
  if (!clause123) {
    throw new Error("12.3 заалт олдсонгүй");
  }
  for (const text of COMMENTS) {
    await prisma.comment.create({ data: { clauseId: clause123.id, body: text } });
  }
  console.log(`\n══ 2. 12.3 дээр ${COMMENTS.length} санал нэмлээ`);

  // 3. Шүүх → бүлэглэх → хариуны ноорог (AI)
  const result = await groupBillComments(id);
  console.log(`\n══ 3. Бүлэглэлт: ${result.newComments} шинэ санал, ${result.filtered} шүүгдсэн, ${result.groups} бүлэг`);

  // 4. Ажилтны харагдац
  detail = await getBillDetail(id, true);
  const staffClause = detail!.clauses.find((c) => c.number === "12.3")!;
  for (const g of staffClause.groups) {
    console.log(`   ■ ${g.title} (${g.commentCount} санал) — ноорог: ${g.replyDraft?.slice(0, 80)}...`);
  }
  for (const f of staffClause.filtered) {
    console.log(`   ✗ ${f.filterStatus.padEnd(9)} «${f.text.slice(0, 40)}» — ${f.filterReason}`);
  }

  // 5. Иргэний харагдац: шүүгдсэн санал харагдах ёсгүй
  const citizen = await getBillDetail(id, false);
  const citizenClause = citizen!.clauses.find((c) => c.number === "12.3")!;
  console.log(`\n══ 5. Иргэнд шүүгдсэн санал харагдах уу? ${citizenClause.filtered.length === 0 ? "Үгүй ✓" : "ТИЙМ ✗"}`);

  // 6. Давтан бүлэглэхэд шинэ бүлэг үүсэхгүй байх ёстой (санал бүр нэг л удаа)
  const again = await groupBillComments(id);
  console.log(`══ 6. Давтан бүлэглэхэд шинэ бүлэг: ${again.groups} ${again.groups === 0 ? "✓" : "✗"}`);

  console.log(`\nАжилтан: http://localhost:3000/staff/bills/${id}`);
  console.log(`Иргэн  : http://localhost:3000/bills/${id}`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exitCode = 1;
  })
  .finally(() => prisma.$disconnect());
