import { explainChange } from "../lib/ai/explain";

// Жишээ төслийн үндэслэл (танилцуулга).
// Анхаар: энд 12.3 (гомдлын хугацаа)-ын шалтгаан БАЙГАА, харин 10.4 (мэдээлэл нийтлэх)-ийн шалтгаан БАЙХГҮЙ.
const REASON_TEXT = `ХУУЛИЙН ТӨСЛИЙН ҮНДЭСЛЭЛ
Улаанбаатар хотын агаарын бохирдлын гол эх үүсвэр нь гэр хорооллын зуухны түлш юм. Одоогийн хуулиар агаарын бохирдлын талаарх иргэний гомдлыг 30 хоногийн дотор шийдвэрлэдэг нь хэт урт бөгөөд бохирдлын улирал өнгөрсний дараа хариу ирэх тохиолдол олон байна. Иймд гомдол шийдвэрлэх хугацааг 14 хоног болгож богиносгох шаардлагатай. Мөн дугуй, хуванцар зэрэг шатах тослог материал шатаах явдал нэмэгдсэн тул хориглох түлшний жагсаалтад нэмэх нь зүйтэй.`;

// Турших 3 тохиолдол
const TESTS = [
  {
    name: "1. Үг солих (12.3) — үндэслэлд шалтгаан байгаа",
    oldText: "Агаарын бохирдлын талаарх иргэний гомдлыг холбогдох байгууллага 30 хоногийн дотор шийдвэрлэнэ.",
    newText: "Агаарын бохирдлын талаарх иргэний гомдлыг холбогдох байгууллага 14 хоногийн дотор шийдвэрлэнэ.",
    reasonText: REASON_TEXT,
  },
  {
    name: "2. Шинэ заалт нэмэх (10.4) — үндэслэлд шалтгаан БАЙХГҮЙ (AI зохиох ёсгүй)",
    oldText: "",
    newText:
      "Нийслэлийн Засаг дарга агаарын чанарын хэмжилтийн мэдээллийг цаг тутам олон нийтэд нээлттэй нийтэлнэ.",
    reasonText: REASON_TEXT,
  },
  {
    name: "3. Хүчингүй болгох (18.5) — үндэслэл огт байхгүй",
    oldText: "Гэр хорооллын айл өрх агаарын бохирдлын төлбөрийг жил бүр төлнө.",
    newText: "",
    reasonText: "",
  },
];

async function main() {
  console.log("AI_STUB =", process.env.AI_STUB || "(тохируулаагүй)");
  console.log("");

  for (const test of TESTS) {
    console.log("══", test.name);
    console.log("   Хуучин:", test.oldText || "(байхгүй)");
    console.log("   Шинэ  :", test.newText || "(байхгүй)");

    const result = await explainChange(test.oldText, test.newText, test.reasonText);

    console.log("   → Юу    :", result.what);
    console.log("   → Яагаад:", result.why);
    console.log("   → Хэнд  :", result.who);
    console.log("");
  }
}

main();
