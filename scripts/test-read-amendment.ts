import { existsSync, readFileSync } from "fs";
import { readAmendment } from "../lib/ai/amendment";

// data/bill.txt байхгүй үед ашиглах жишээ төсөл.
// Хүлээгдэж буй хариу: 9 өөрчлөлт (9 дүгээр зүйл нь өөрчлөлт биш тул алгасна).
// 7, 8 дугаар зүйл = "гэсний дараа ... гэж нэмсүгэй" → REPLACE_WORDS болж гарах ёстой:
//   21.1: "иргэн" → "иргэн, хуулийн этгээд"
//   22.3: "төрийн байгууллага" → "төрийн байгууллага болон орон нутгийн өөрөө удирдах байгууллага"
const SAMPLE_BILL = `АГААРЫН ТУХАЙ ХУУЛЬД НЭМЭЛТ, ӨӨРЧЛӨЛТ ОРУУЛАХ ТУХАЙ

1 дүгээр зүйл.Агаарын тухай хуулийн 10 дугаар зүйлд доор дурдсан агуулгатай 10.4 дэх хэсэг нэмсүгэй:
“10.4.Нийслэлийн Засаг дарга агаарын чанарын хэмжилтийн мэдээллийг цаг тутам олон нийтэд нээлттэй нийтэлнэ.”

2 дугаар зүйл.Агаарын тухай хуулийн 12 дугаар зүйлийн 12.2 дахь хэсгийн “түүхий нүүрс” гэснийг “түүхий нүүрс, шатах тослог материал” гэж, 12.3 дахь хэсгийн “30 хоногийн” гэснийг “14 хоногийн” гэж тус тус өөрчилсүгэй.

3 дугаар зүйл.Агаарын тухай хуулийн 15 дугаар зүйлийн 15.1 дэх хэсгийг доор дурдсанаар өөрчлөн найруулсугай:
“15.1.Агаарын бохирдлыг бууруулах үндэсний хорооны бүрэлдэхүүнд иргэний нийгмийн байгууллагын хоёроос доошгүй төлөөлөл оролцоно.”

4 дүгээр зүйл.Агаарын тухай хуулийн 18 дугаар зүйлийн 18.5 дахь хэсгийг хүчингүй болсонд тооцсугай.

5 дугаар зүйл.Агаарын тухай хуулийн 3 дугаар зүйлийн 3.1 дэх хэсгийн “хариуцлагатай байна” гэснийг “хариуцлагатай байж болно” гэж өөрчилсүгэй.

6 дугаар зүйл.Агаарын тухай хуулийн 20 дугаар зүйлийн 20.2 дахь хэсгийн “хүндэтгэн үзэх шалтгаангүйгээр” гэснийг хассугай.

7 дугаар зүйл.Агаарын тухай хуулийн 21 дүгээр зүйлийн 21.1 дэх хэсгийн “иргэн” гэсний дараа “, хуулийн этгээд” гэж нэмсүгэй.

8 дугаар зүйл.Агаарын тухай хуулийн 22 дугаар зүйлийн 22.3 дахь хэсгийн “төрийн байгууллага” гэсний дараа “болон орон нутгийн өөрөө удирдах байгууллага” гэж нэмсүгэй.

9 дүгээр зүйл.Энэ хуулийг 2027 оны 01 дүгээр сарын 01-ний өдрөөс эхлэн дагаж мөрдөнө.`;

async function main() {
  // 1. Төслийн текстийг бэлдэнэ: data/bill.txt байвал түүнийг, үгүй бол жишээг ашиглана.
  //    (Зам нь төслийн үндсэн хавтаснаас эхэлнэ — скриптийг тэндээс ажиллуулна.)
  let billText = SAMPLE_BILL;
  if (existsSync("data/bill.txt")) {
    billText = readFileSync("data/bill.txt", "utf-8");
    console.log("Төслийг data/bill.txt файлаас уншлаа.");
  } else {
    console.log("data/bill.txt байхгүй тул жишээ төсөл ашиглаж байна.");
  }
  console.log("AI_STUB =", process.env.AI_STUB || "(тохируулаагүй)");
  console.log("");

  // 2. AI-аар төслийг уншуулна
  const changes = await readAmendment(billText);

  // 3. Өөрчлөлт бүрийг хэвлэнэ
  for (let i = 0; i < changes.length; i++) {
    const change = changes[i];
    console.log(`[${i + 1}] ${change.action} — ${change.clause}`);
    if (change.oldWords !== undefined) {
      console.log(`    Хуучин үг : ${change.oldWords}`);
    }
    if (change.newText !== undefined) {
      console.log(`    Шинэ текст: ${change.newText === "" ? "(хасна)" : change.newText}`);
    }
    console.log(`    Ишлэл     : ${change.sourceQuote}`);
    console.log("");
  }

  console.log(`Нийт: ${changes.length} өөрчлөлт`);
}

main();
