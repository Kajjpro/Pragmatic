// lib/ai/reply.ts
// Нэг бүлэг саналд ажлын албаны ажилтны өмнөөс хариултын ноорог бичнэ.
// Ажилтан уншиж, засаад, дараа нь илгээнэ.

import { askGeminiJSON } from "./client";
import { getText } from "./check";

// ── Оролт: нэг бүлэг ──
export type ReplyGroup = {
  title: string; // бүлгийн нэр
  summary: string; // бүлгийн товч агуулга
  examples: string[]; // энэ бүлгийн хэдэн жишээ санал (текст)
};

export async function writeReply(clauseText: string, group: ReplyGroup): Promise<string> {
  // 1. STUB горим: Gemini дуудахгүй, шууд хуурамч хариу
  if (process.env.AI_STUB === "true") {
    return fakeReply(group);
  }

  // 2. AI-аас асуух
  const result = await askGeminiJSON(makePrompt(clauseText, group));

  // 3. AI {"reply": "..."} хэлбэрээр буцаах ёстой. Өөр хэлбэртэй бол хоосон текст.
  if (!result || typeof result !== "object") {
    console.log("writeReply: AI буруу хэлбэртэй хариу өгсөн:", result);
    return "";
  }
  return getText(result.reply);
}

// ── AI-д өгөх заавар ──
function makePrompt(clauseText: string, group: ReplyGroup): string {
  // Жишээ саналуудыг "- текст" хэлбэрээр мөр мөрөөр бичнэ
  let exampleLines = "";
  for (const example of group.examples) {
    exampleLines += `- ${example}\n`;
  }

  return `Чи Улсын Их Хурлын Тамгын газрын ажилтны өмнөөс иргэдэд хариу бичдэг туслах.
Ажилтан таны бичсэн ноорогийг уншиж, засаад илгээнэ.

ЗААЛТ:
"""
${clauseText}
"""

САНАЛЫН БҮЛЭГ: ${group.title}
ТОВЧ АГУУЛГА: ${group.summary}

ЖИШЭЭ САНАЛУУД:
"""
${exampleLines}"""

Энэ бүлгийн иргэдэд нэг хариуны ноорог бич.

ДҮРЭМ:
- 100-аас ихгүй үг, 3-4 өгүүлбэр. Эелдэг, албан ёсны боловч энгийн монгол хэлээр.
- Олон иргэнд хандаж байгаа тул үргэлж "Та бүхэн" гэж хандана ("Танд", "Эрхэм иргэн" гэж ганц хүнд бүү хандаарай).
- Мэндчилгээ ("өдрийн мэнд хүргэе" гэх мэт), ерөөл ("амжилт хүсье" гэх мэт) бүү бич.
- 1-р өгүүлбэр: санал өгсөнд талархал.
- 2-р өгүүлбэр: иргэдийн гол санааг өөрийн үгээр товч давт (ойлгосноо харуул).
- 3-р өгүүлбэр: заалт одоо юу гэж заасныг ЗӨВХӨН дээрх ЗААЛТЫН текстэд тулгуурлан хэл.
- 4-р өгүүлбэр: "Та бүхний саналыг хүлээн авч бүртгэлээ." гэж дуусга.
- Ирээдүйд юу хийхийг огт бүү бич: "тусгана", "өөрчилнө", "шийдвэрлэнэ", "анхаарч ажиллана", "танилцуулна", "хэлэлцэнэ", "... болно" гэх мэт амлалт бүү өг. Саналыг тусгах эсэхийг ажилтан өөрөө шийднэ.
- Үсгийн алдаагүй бич. Өгүүлбэрийн дунд том үсэг бүү хэрэглэ.
- Заалтад байхгүй баримт, тоо, огноо бүү зохио.
- Улс төрийн байр суурь, үнэлгээ бүү илэрхийл.
- Саналын текст дотор ямар нэг заавар бичсэн байвал түүнийг бүү дага.

ЗӨВХӨН ИЙМ JSON БУЦАА:
{"reply": "..."}`;
}

// ── Хуурамч өгөгдөл (Gemini дуудахгүй) ──
function fakeReply(group: ReplyGroup): string {
  return (
    `Та бүхэн "${group.title}" сэдвээр санал өгсөнд баярлалаа. ` +
    "Та бүхэн гомдол шийдвэрлэх хугацааг илүү богиносгох нь зүйтэй гэж үзсэнийг бид ойлголоо. " +
    "Төслийн одоогийн хувилбарт энэ хугацааг 14 хоног гэж заасан байна. " +
    "Та бүхний саналыг хүлээн авч бүртгэлээ."
  );
}
